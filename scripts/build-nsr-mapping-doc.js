// Writes docs/api/nsr-field-mapping.md from server/integrations/nsr/mapping.json, so the document and the code
// cannot disagree. tests/nsr.test.js fails if the committed document is out of date.
// Run from the repo root:  node scripts/build-nsr-mapping-doc.js
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const M = require('../server/integrations/nsr/mapping.json');
const SCHEMA = require('../prototype/schema.js');

const OUT = path.join(__dirname, '../docs/api/nsr-field-mapping.md');
const FIELDS = new Map(SCHEMA.fields.map((f) => [f.name, f]));
const SECTIONS = {
  context: 'Context keys (top level, as in the specification examples)',
  survey_consent: '1. Survey and consent',
  composition_and_headship: '2. Composition and headship',
  dwelling_and_services: '3. Dwelling and services',
  vulnerability_shocks_and_coping: '4. Vulnerability, shocks and coping',
  household_health_insurance: '5. Household health insurance',
  household_assets_inventory: '6. Household assets inventory',
  household_crops_grown: '7. Household crops grown',
  household_members: '8. Household members roster (per member)',
};
const TRANSFORMS = {
  copy: 'none', code: 'code sent unchanged', yes_no: 'true/false -> YES/NO', code_map: 'code -> NSR value', code_label: 'code -> year',
  multi_codes: 'list -> space-separated codes', count_flag: 'count > 0 -> YES, 0 -> NO', count_num: 'count -> string', assets_any: 'any asset count > 0',
  crops_any: 'any crop answer present', crop_flag: 'crop code in crops_grown', other_crop_flag: 'other crop text present', birth_year: 'year of birth_date',
  birth_month: 'month of birth_date', birth_day: 'day of birth_date', age: 'completed years at message time', subsector: 'only under the sector\'s key',
  social_any: 'any group membership true', gps_components: 'sent as latitude, longitude, accuracy_m', none: 'not sent',
};
const cell = (s) => String(s === null || s === undefined ? '' : s).replace(/\|/g, '\\|').replace(/\n/g, ' ');
const code = (s) => (s === null || s === undefined || s === '' ? '' : '`' + s + '`');

function row(e) {
  const src = e.source === 'asset_*' ? 'all `asset_*`' : e.source === 'member_*' ? 'the five `member_*` groups' : e.source ? code(e.source) : '—';
  const values = e.values ? ' ' + Object.entries(e.values).map(([k, v]) => `${k}→${v}`).join(', ') + (e.fallback ? `, other→${e.fallback}` : '') : '';
  const type = e.source && FIELDS.get(e.source) ? FIELDS.get(e.source).type : e.type;
  const exists = e.source ? 'Yes' : 'No';
  const extra = e.transform === 'none' ? (e.classification === 'MISSING' ? 'Yes: not collected' : 'Needs NSR answer') : 'No';
  return `| ${code(e.target)} | ${src} | ${e.aliases.map(code).join(', ')} | ${cell(TRANSFORMS[e.transform] + values)} | ${cell(type)} | ${e.spec_default === null ? '' : code(JSON.stringify(e.spec_default))} | ${exists} | ${e.classification === 'DERIVED' ? 'Yes' : e.transform === 'none' ? 'No' : '—'} | ${extra} | **${e.classification}** | ${cell(e.notes)} |`;
}

function render() {
  const all = [...M.household, ...M.members];
  const count = (c) => all.filter((e) => e.section !== 'context' && e.classification === c).length;
  const L = [];
  L.push('# NSR field mapping: CCT DataBridge to OpenG2P NSR household intake');
  L.push('');
  L.push('<!-- Generated by scripts/build-nsr-mapping-doc.js from server/integrations/nsr/mapping.json. Do not edit by hand. -->');
  L.push('');
  L.push(`Source of truth: \`server/integrations/nsr/mapping.json\` (machine-readable; the mapper interprets it, tests check it against the specification). Specification: \`${M.spec.document}\` v${M.spec.version}. Canonical schema: \`prototype/schema.js\` (145 fields, from \`NSR_Registry_Build_Sheet.xlsx\` > Create Fields, whose *NSR source* column names the NSR form field for each canonical field).`);
  L.push('');
  L.push('## Summary');
  L.push('');
  L.push(`- The specification names **${M.household.filter((e) => e.section !== 'context').length} household fields** (sections 1-7) and **${M.members.length} fields per member** (section 8): ${M.household.filter((e) => e.section !== 'context').length + M.members.length} in all. DataBridge holds **145** canonical fields. They are not one-to-one.`);
  L.push(`- Classification of the ${all.filter((e) => e.section !== 'context').length} specification fields: ${Object.keys(M.classifications).map((c) => `${c} ${count(c)}`).join(', ')}.`);
  L.push(`- ${Object.keys(M.not_sent).length} canonical fields have no NSR field and are not sent (listed at the end).`);
  L.push('- Rule: **a key is sent only when DataBridge holds a value for it.** No defaults are filled in, and missing answers are never turned into "NO".');
  L.push('- Consent is always sent and must be `true` on every member record; otherwise the household is blocked (`CONSENT_NOT_GIVEN` / `CONSENT_MISSING`).');
  L.push('');
  L.push('Classifications:');
  L.push('');
  for (const [k, v] of Object.entries(M.classifications)) L.push(`- **${k}**: ${v}`);
  L.push('');
  L.push('## Household grouping');
  L.push('');
  L.push('DataBridge stores one record per person, with household values repeated on each. The mapper builds one NSR household from all records sharing an `nsr_household_serial`:');
  L.push('');
  L.push('- **Head**: the record with `is_household_head = true` or `relationship_to_head = "1"`. None, more than one, or the two fields disagreeing blocks the household (`NO_HEAD`, `MULTIPLE_HEADS`, `HEAD_CONFLICT`).');
  L.push('- **Household values** (every field whose build-sheet object is *Household*) are taken once. If members carry different values the household is blocked (`HOUSEHOLD_FIELD_CONFLICT`); DataBridge never picks one. In the seeded demo data this blocks 9 of 13 households, because the synthetic generator gives members of one household different addresses and dwelling values.');
  L.push('- **`member_count`** must equal the number of member records (`MEMBER_COUNT_MISMATCH`), so `total_heads` always matches `household_members`.');
  L.push('- **Duplicates**: two records with the same NIN, or the same name and birth date, block the household (`DUPLICATE_MEMBER`).');
  L.push('- **Order**: head first, then by `internal_record_id`, so the same records always produce the same payload.');
  L.push('- **Limits**: more than `NSR_WEBHOOK_MAX_MEMBERS` (default 50) members blocks the household (`TOO_MANY_MEMBERS`); nothing is truncated.');
  L.push('- The stored records are never changed. The household `content_hash` is computed from the source records (not the payload, whose `age` changes with the date) and drives duplicate-submission protection.');
  L.push('');
  L.push('## Mapping matrix');
  L.push('');
  L.push('Columns: target NSR field; DataBridge source; keys the NSR template accepts (from the specification); transformation; DataBridge data type; NSR default when the key is absent (from the specification); whether the source exists; whether it is derived; whether more source data is needed; classification; notes.');
  for (const [sec, title] of Object.entries(SECTIONS)) {
    const rows = all.filter((e) => e.section === sec);
    L.push('');
    L.push(`### ${title} (${rows.length})`);
    L.push('');
    L.push('| NSR field | DataBridge source | Accepted keys | Transformation | Type | NSR default | Source exists | Derived | Needs more data | Class | Notes |');
    L.push('|---|---|---|---|---|---|---|---|---|---|---|');
    for (const e of rows) L.push(row(e));
  }
  L.push('');
  L.push('## Source fields DataBridge does not have');
  L.push('');
  L.push('These specification fields are never sent. Fields marked REVIEW_REQUIRED here need a decision, not just data.');
  L.push('');
  for (const e of all.filter((x) => x.transform === 'none')) L.push(`- ${code(e.target)} (${SECTIONS[e.section]}): **${e.classification}**. ${e.notes}`);
  L.push('');
  L.push('## Where the specification\'s defaults conflict with DataBridge data');
  L.push('');
  L.push('The NSR template fills a default for an absent key. DataBridge never sends a value it does not hold, so for these fields the NSR record can show something DataBridge never collected. The preview lists each case as a `NSR_DEFAULT_APPLIES` warning.');
  L.push('');
  L.push('| NSR field | NSR default | Effect when DataBridge has no value |');
  L.push('|---|---|---|');
  for (const e of all.filter((x) => x.spec_default !== null && x.spec_default !== '' && !(x.section === 'household_crops_grown' && x.target !== 'hh_crops_options'))) {
    L.push(`| ${code(e.target)} | ${code(JSON.stringify(e.spec_default))} | ${cell(e.target === 'consent' ? 'Never reached: consent is always sent, and the household is blocked without it.' : e.target === 'hh_crops_options' ? 'NSR records "NO" for every crop and other_crop, although the crops were never asked.' : e.notes || 'NSR records the default.')} |`);
  }
  L.push('');
  L.push('**Question for the NSR team:** can the template leave an absent key empty instead of applying these defaults? Until then, households without these values reach NSR with defaults DataBridge did not collect.');
  L.push('');
  L.push('## Canonical fields that are not sent');
  L.push('');
  L.push('| DataBridge field | Reason |');
  L.push('|---|---|');
  for (const [k, v] of Object.entries(M.not_sent)) L.push(`| ${code(k)} | ${cell(v)} |`);
  L.push('');
  return L.join('\n');
}

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
}
module.exports = { render, OUT };
